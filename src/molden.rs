//! Molden file export for molecular orbital visualization.
//! Formats: [Molden Format], [Atoms] AU, [GTO], and [MO].
//! Compatible with standard visualization tools (Jmol, Molden, Avogadro, VMD, Chemcraft).

use crate::basis::{Atom, BasisSetMap};
use crate::scf::{HFResult, UHFResult};
use std::fs::File;
use std::io::{self, Write};

fn component_order(
    basis: &[crate::basis::ContractedGaussian],
    spherical: bool,
) -> Result<Vec<usize>, crate::error::HfError> {
    use crate::error::HfError;
    let shells = crate::ao::shell_ranges(basis)?;
    let mut order = Vec::new();
    let mut offset = 0;
    for range in shells {
        let l = basis[range.start].total_angular_momentum();
        if l > 4 {
            return Err(HfError::InvalidInput(
                "Molden supports shells only through g (L=4)".into(),
            ));
        }
        if spherical {
            if l <= 1 {
                order.extend(offset..offset + 2 * l + 1);
            } else {
                order.push(offset + l);
                for m in 1..=l {
                    order.push(offset + l + m);
                    order.push(offset + l - m);
                }
            }
            offset += 2 * l + 1;
        } else {
            let powers = match l {
                0 => vec![[0, 0, 0]],
                1 => vec![[1, 0, 0], [0, 1, 0], [0, 0, 1]],
                2 => vec![
                    [2, 0, 0],
                    [0, 2, 0],
                    [0, 0, 2],
                    [1, 1, 0],
                    [1, 0, 1],
                    [0, 1, 1],
                ],
                3 => vec![
                    [3, 0, 0],
                    [0, 3, 0],
                    [0, 0, 3],
                    [1, 2, 0],
                    [2, 1, 0],
                    [2, 0, 1],
                    [1, 0, 2],
                    [0, 1, 2],
                    [0, 2, 1],
                    [1, 1, 1],
                ],
                4 => vec![
                    [4, 0, 0],
                    [0, 4, 0],
                    [0, 0, 4],
                    [3, 1, 0],
                    [3, 0, 1],
                    [1, 3, 0],
                    [0, 3, 1],
                    [1, 0, 3],
                    [0, 1, 3],
                    [2, 2, 0],
                    [2, 0, 2],
                    [0, 2, 2],
                    [2, 1, 1],
                    [1, 2, 1],
                    [1, 1, 2],
                ],
                _ => unreachable!(),
            };
            for power in powers {
                order.push(
                    range
                        .clone()
                        .find(|&i| basis[i].l == power)
                        .ok_or_else(|| {
                            HfError::InvalidInput("missing Cartesian component".into())
                        })?,
                );
            }
        }
    }
    Ok(order)
}

fn header(
    atoms: &[Atom],
    map: &BasisSetMap,
    spherical: bool,
) -> Result<(String, Vec<usize>), crate::error::HfError> {
    use crate::error::HfError;
    for atom in atoms {
        if !map.contains_key(&atom.symbol.to_uppercase()) {
            return Err(HfError::InvalidInput(format!(
                "Missing basis for {}",
                atom.symbol
            )));
        }
    }
    let basis = crate::basis::try_build_basis(atoms, map)?;
    let order = component_order(&basis, spherical)?;
    let mut out = String::from("[Molden Format]\n[Title]\nGenerated by hf-rs\n[Atoms] AU\n");
    for (i, atom) in atoms.iter().enumerate() {
        out.push_str(&format!(
            "{} {} {} {:.16e} {:.16e} {:.16e}\n",
            atom.symbol,
            i + 1,
            atom.atomic_number,
            atom.position[0],
            atom.position[1],
            atom.position[2]
        ));
    }
    out.push_str("\n[GTO]\n");
    // Recover normalized radial contraction coefficients from the actual basis.
    // This also handles arbitrary scaling of a supplied contraction vector.
    for (a, _) in atoms.iter().enumerate() {
        out.push_str(&format!("{} 0\n", a + 1));
        for range in crate::ao::shell_ranges(&basis)? {
            let cg = &basis[range.start];
            if cg.atom_index != a {
                continue;
            }
            out.push_str(&format!(
                " {} {} 1.00\n",
                crate::basis::l_to_shell_type(cg.total_angular_momentum()).to_lowercase(),
                cg.primitives.len()
            ));
            for prim in &cg.primitives {
                let coefficient =
                    prim.coefficient / crate::basis::primitive_norm(prim.exponent, cg.l);
                out.push_str(&format!(" {:.16e} {:.16e}\n", prim.exponent, coefficient));
            }
        }
        out.push('\n');
    }
    out.push_str(if spherical {
        "[5D7F]\n[9G]\n"
    } else {
        "[6D]\n[10F]\n[15G]\n"
    });
    if atoms.iter().any(|a| a.ecp.is_some()) {
        out.push_str("[core]\n");
        for (i, atom) in atoms.iter().enumerate() {
            if let Some(ecp) = &atom.ecp {
                out.push_str(&format!("{} : {}\n", i + 1, ecp.n_core));
            }
        }
    }
    out.push_str("[MO]\n");
    Ok((out, order))
}

fn write_orbitals(
    out: &mut String,
    order: &[usize],
    c: &crate::matrix::Matrix,
    eps: &[f64],
    n_occ: usize,
    occupation: f64,
    spin: &str,
) -> Result<(), crate::error::HfError> {
    if c.cols != eps.len()
        || order.iter().any(|&i| i >= c.rows)
        || order.len() != c.rows
        || n_occ > c.cols
    {
        return Err(crate::error::HfError::InvalidInput(
            "Molden orbital dimensions do not match basis".into(),
        ));
    }
    for mo in 0..c.cols {
        out.push_str(&format!(
            "Sym= A\nEne= {:.16e}\nSpin= {}\nOccup= {:.8}\n",
            eps[mo],
            spin,
            if mo < n_occ { occupation } else { 0.0 }
        ));
        for (index, &row) in order.iter().enumerate() {
            out.push_str(&format!("{} {:.16e}\n", index + 1, c[(row, mo)]));
        }
    }
    Ok(())
}

pub fn try_generate_molden_string_rhf(
    atoms: &[Atom],
    map: &BasisSetMap,
    hf: &HFResult,
) -> Result<String, crate::error::HfError> {
    let spherical = hf
        .ao_space
        .as_ref()
        .is_some_and(|s| s.kind == crate::ao::BasisKind::Spherical);
    let (mut out, order) = header(atoms, map, spherical)?;
    let physical = if let Some(space) = &hf.ao_space {
        space.physical_coefficients(&hf.mo_coefficients)?
    } else {
        hf.mo_coefficients.clone()
    };
    write_orbitals(
        &mut out,
        &order,
        &physical,
        &hf.orbital_energies,
        hf.n_occ,
        2.0,
        "Alpha",
    )?;
    Ok(out)
}
pub fn try_generate_molden_string_uhf(
    atoms: &[Atom],
    map: &BasisSetMap,
    hf: &UHFResult,
) -> Result<String, crate::error::HfError> {
    let spherical = hf
        .ao_space
        .as_ref()
        .is_some_and(|s| s.kind == crate::ao::BasisKind::Spherical);
    let (mut out, order) = header(atoms, map, spherical)?;
    for (c, eps, n_occ, spin) in [
        (
            &hf.mo_coefficients_alpha,
            &hf.orbital_energies_alpha,
            hf.n_alpha,
            "Alpha",
        ),
        (
            &hf.mo_coefficients_beta,
            &hf.orbital_energies_beta,
            hf.n_beta,
            "Beta",
        ),
    ] {
        let physical = if let Some(space) = &hf.ao_space {
            space.physical_coefficients(c)?
        } else {
            c.clone()
        };
        write_orbitals(&mut out, &order, &physical, eps, n_occ, 1.0, spin)?;
    }
    Ok(out)
}

pub fn generate_molden_string_rhf(atoms: &[Atom], map: &BasisSetMap, hf: &HFResult) -> String {
    try_generate_molden_string_rhf(atoms, map, hf).expect("Molden export failed")
}
pub fn generate_molden_string_uhf(atoms: &[Atom], map: &BasisSetMap, hf: &UHFResult) -> String {
    try_generate_molden_string_uhf(atoms, map, hf).expect("Molden export failed")
}

/// Writes RHF calculation results to a Molden file on disk.
pub fn write_molden_file_rhf(
    atoms: &[Atom],
    basis_map: &BasisSetMap,
    hf_res: &HFResult,
    path: &str,
) -> io::Result<()> {
    let content = try_generate_molden_string_rhf(atoms, basis_map, hf_res)
        .map_err(|e| io::Error::new(io::ErrorKind::InvalidInput, e))?;
    let mut file = File::create(path)?;
    file.write_all(content.as_bytes())
}

/// Writes UHF calculation results to a Molden file on disk.
pub fn write_molden_file_uhf(
    atoms: &[Atom],
    basis_map: &BasisSetMap,
    uhf_res: &UHFResult,
    path: &str,
) -> io::Result<()> {
    let content = try_generate_molden_string_uhf(atoms, basis_map, uhf_res)
        .map_err(|e| io::Error::new(io::ErrorKind::InvalidInput, e))?;
    let mut file = File::create(path)?;
    file.write_all(content.as_bytes())
}
