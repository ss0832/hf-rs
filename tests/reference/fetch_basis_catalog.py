def fetch(url):
    request = Request(url, headers={"User-Agent": "hf-rs-basis-data/0.3.0"})
    with urlopen(request, timeout=60) as response:
        return response.read()


def main():
    data_dir = DESTINATION / "data"
    data_dir.mkdir(parents=True, exist_ok=True)
    records = []
    for index, name in enumerate(ADDITIONAL_ORBITAL):
        stem = "orbital_{:02d}".format(index)
        url = "https://www.basissetexchange.org/api/basis/{}/format/json/".format(
            quote(name, safe="")
        )
        path = data_dir / (stem + ".json")
        raw = path.read_bytes() if path.exists() else fetch(url)
        data = json.loads(raw)
        assert data["name"].casefold() == name.casefold(), (name, data["name"])
        assert data["elements"] and all(
            el.get("electron_shells") for el in data["elements"].values()
        )
        path.write_bytes(raw)
        version = data["version"]
        g94_url = "https://www.basissetexchange.org/api/basis/{}/format/gaussian94/?version={}".format(
            quote(name, safe=""), quote(str(version))
        )
        g94_path = data_dir / (stem + ".gbs")
        g94 = g94_path.read_bytes() if g94_path.exists() else fetch(g94_url)
        g94_path.write_bytes(g94)
        records.append(
            dict(
                name=name,
                version=version,
                json_file=path.name,
                json_url=url,
                json_sha256=hashlib.sha256(raw).hexdigest(),
                gaussian94_file=g94_path.name,
                gaussian94_url=g94_url,
                gaussian94_sha256=hashlib.sha256(g94).hexdigest(),
                elements=sorted(int(z) for z in data["elements"]),
                ecp_elements=sorted(
                    int(z)
                    for z, el in data["elements"].items()
                    if el.get("ecp_potentials")
                ),
            )
        )
        print(
            "Fetched {}: {} elements, version {}".format(
                name, len(data["elements"]), version
            ),
            flush=True,
        )
    license_url = (
        "https://raw.githubusercontent.com/MolSSI-BSE/basis_set_exchange/master/LICENSE"
    )
    license_data = fetch(license_url)
    (DESTINATION / "LICENSE").write_bytes(license_data)
    manifest = dict(
        source="Basis Set Exchange official numerical exports",
        retrieved="2026-10-28",
        license_url=license_url,
        license_sha256=hashlib.sha256(license_data).hexdigest(),
        basis_sets=records,
    )
    (DESTINATION / "manifest.json").write_text(
        json.dumps(manifest, indent=2) + "\n", encoding="utf-8"
    )
    lines = [
        "// SPDX-License-Identifier: Apache-2.0",
        "// Copyright (c) 2026 ss0832",
        "//",
        "// This code is part of the hf-rs library.",
        "",
        "//! Additional BSE numerical exports; see third_party/basis_set_exchange.",
        "//! Generated by tests/reference/fetch_basis_catalog.py.",
        "",
        "pub(crate) const ORBITAL: &[(&str, &str)] = &[",
    ]
    for entry in records:
        lines.append(
            '    ({}, include_str!("../third_party/basis_set_exchange/data/{}")),'.format(
                json.dumps(entry["name"]), entry["json_file"]
            )
        )
    lines.extend(
        [
            "];",
            "",
            "pub(crate) fn json(name: &str) -> Option<&'static str> {",
            "    let normalized = crate::basis::normalize_basis_name(name);",
            "    ORBITAL.iter().find_map(|&(canonical, data)| {",
            "        (crate::basis::normalize_basis_name(canonical) == normalized).then_some(data)",
            "    })",
            "}",
            "",
        ]
    )
    (ROOT / "src/builtin_catalog.rs").write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    main()
