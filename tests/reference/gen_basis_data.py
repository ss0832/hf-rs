"""Regenerates src/basis_data.rs from the Basis Set Exchange (basis_set_exchange Python package).

Every constant holds the complete element coverage of the BSE basis set in Gaussian 94 format.
Effective core potentials (def2, Z = 37-86) are written to the separate constant ECP_DEF2_GBS.
Usage: python tests/reference/gen_basis_data.py > src/basis_data.rs
"""

import basis_set_exchange as bse

NL = "\n"

# (rust constant, BSE name)
ORBITAL = [
    ("STO_3G_GBS", "sto-3g"),
    ("BASIS_3_21G_GBS", "3-21g"),
    ("BASIS_6_31G_GBS", "6-31g"),
    ("BASIS_6_31G_STAR_GBS", "6-31g_st_"),
    ("BASIS_6_31G_STAR_STAR_GBS", "6-31g_st__st_"),
    ("BASIS_6_311G_SS_GBS", "6-311g_st__st_"),
    ("BASIS_DEF2_SVP_GBS", "def2-svp"),
    ("BASIS_DEF2_TZVP_GBS", "def2-tzvp"),
    ("BASIS_DEF2_QZVP_GBS", "def2-qzvp"),
    ("BASIS_CC_PVDZ_GBS", "cc-pvdz"),
    ("BASIS_CC_PVTZ_GBS", "cc-pvtz"),
    ("BASIS_CC_PVQZ_GBS", "cc-pvqz"),
    ("BASIS_AUG_CC_PVDZ_GBS", "aug-cc-pvdz"),
    ("BASIS_AUG_CC_PVTZ_GBS", "aug-cc-pvtz"),
]
AUXILIARY = [
    ("AUX_DEF2_UNIVERSAL_JKFIT_GBS", "def2-universal-jkfit"),
    ("AUX_DEF2_SVP_RIFIT_GBS", "def2-svp-rifit"),
    ("AUX_DEF2_TZVP_RIFIT_GBS", "def2-tzvp-rifit"),
    ("AUX_CC_PVDZ_RIFIT_GBS", "cc-pvdz-rifit"),
    ("AUX_CC_PVTZ_RIFIT_GBS", "cc-pvtz-rifit"),
    ("AUX_AUG_CC_PVDZ_RIFIT_GBS", "aug-cc-pvdz-rifit"),
    ("AUX_CC_PVDZ_F12_OPTRI_GBS", "cc-pvdz-f12-optri"),
    ("AUX_CC_PVTZ_F12_OPTRI_GBS", "cc-pvtz-f12-optri"),
]

meta = bse.get_metadata()

print("// SPDX-License-Identifier: Apache-2.0")
print("// Copyright (c) 2026 ss0832")
print("//")
print("// This code is part of the hf-rs library.")
print()
print(
    "//! Built-in orbital and auxiliary basis sets and effective core potentials, generated by"
)
print(
    "//! `tests/reference/gen_basis_data.py` from the Basis Set Exchange (BSE) with full element coverage"
)
print("//! (Gaussian 94 format). DO NOT EDIT BY HAND.")
print()
print(f"// Generated with basis_set_exchange {bse.version()}")
print()

ecp_by_set = {}  # BSE name -> {Z: ECP text}

for group, entries in (
    ("Orbital basis sets", ORBITAL),
    ("Auxiliary (RI / JK / CABS) basis sets", AUXILIARY),
):
    print(f"// ===== {group} =====")
    print()
    for const, name in entries:
        m = meta[name]
        ver = m["latest_version"]
        blocks, ecps = [], {}
        for z in sorted(int(e) for e in m["versions"][ver]["elements"]):
            block = bse.get_basis(
                name, fmt="gaussian94", header=False, elements=[z]
            ).strip()
            idx = block.find("-ECP")
            if idx >= 0:
                # BSE appends "<El>     0" and "<El>-ECP  lmax  ncore ..." after the orbital block.
                ecp_line_start = block.rfind(NL, 0, idx) + 1
                orbital_end = block.rfind(
                    NL, 0, ecp_line_start - 1
                )  # start of the repeated element header
                ecps[z] = block[ecp_line_start:].strip()
                block = block[:orbital_end].strip()
            blocks.append(block)
        if ecps:
            ecp_by_set[name] = ecps
        text = NL.join(blocks)
        assert '"#' not in text
        note = (
            f"; ECPs for Z = {min(ecps)}-{max(ecps)} are in ECP_DEF2_GBS"
            if ecps
            else ""
        )
        print(
            f"/// {m['display_name']} (BSE version {ver}, {len(blocks)} elements{note}), Gaussian 94 format."
        )
        print("pub const " + const + ': &str = r#"' + NL + text + NL + '"#;')
        print()

# The def2 effective core potentials are identical for all def2 sizes.
sets = [n for n in ("def2-svp", "def2-tzvp", "def2-qzvp") if n in ecp_by_set]
for n in sets[1:]:
    assert ecp_by_set[n] == ecp_by_set[sets[0]], f"{n} ECPs differ from {sets[0]}"
zs = sorted(ecp_by_set[sets[0]])
ecp_text = (NL + NL).join(ecp_by_set[sets[0]][z] for z in zs)
assert '"#' not in ecp_text
print("// ===== Effective core potentials =====")
print()
print(
    f"/// def2 effective core potentials (Stuttgart-Koeln; shared by def2-SVP/TZVP/QZVP; Z = {zs[0]}-{zs[-1]}),"
)
print("/// Gaussian 94 ECP format.")
print('pub const ECP_DEF2_GBS: &str = r#"' + NL + ecp_text + NL + '"#;')
